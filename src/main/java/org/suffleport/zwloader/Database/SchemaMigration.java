package org.suffleport.zwloader.Database;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;

import javax.sql.DataSource;

import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.stereotype.Component;

import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;

/**
 * Применение изменений схемы при старте приложения.
 *
 * В проекте нет Flyway, поэтому миграции выполняются обычным JDBC прямо здесь.
 * Все операторы написаны идемпотентно (IF NOT EXISTS / WHERE NOT EXISTS), так что
 * повторный запуск приложения ничего не ломает.
 */
@Component
@RequiredArgsConstructor
@Slf4j
public class SchemaMigration implements ApplicationRunner {

    /**
     * Порядок важен: сначала таблицы, потом внешние ключи и индексы.
     * В тестах H2 создаёт таблицы сам по сущностям, поэтому CREATE TABLE IF NOT EXISTS
     * просто пропускается.
     */
    private static final List<String> MIGRATIONS = List.of(

            // 1. Заявки на гостевой визит
            """
            CREATE TABLE IF NOT EXISTS visit_requests (
                request_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                guest_id            UUID,
                visitor_last_name   VARCHAR(100) NOT NULL,
                visitor_first_name  VARCHAR(100) NOT NULL,
                visitor_middle_name VARCHAR(100),
                organization        VARCHAR(200),
                phone               VARCHAR(32),
                purpose             VARCHAR(300),
                planned_from        TIMESTAMP WITH TIME ZONE NOT NULL,
                planned_to          TIMESTAMP WITH TIME ZONE NOT NULL,
                status              VARCHAR(32) NOT NULL DEFAULT 'DRAFT',
                host_person_id      UUID NOT NULL,
                author_user_id      INTEGER,
                author_email        VARCHAR(200),
                approver_person_id  UUID,
                decision_comment    VARCHAR(1000),
                decided_at          TIMESTAMP WITH TIME ZONE,
                created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
                updated_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
                CONSTRAINT fk_visit_requests_guest    FOREIGN KEY (guest_id) REFERENCES guests(guest_id),
                CONSTRAINT fk_visit_requests_host     FOREIGN KEY (host_person_id) REFERENCES personnel(person_id),
                CONSTRAINT fk_visit_requests_approver FOREIGN KEY (approver_person_id) REFERENCES personnel(person_id),
                CONSTRAINT chk_visit_requests_period  CHECK (planned_to > planned_from)
            )
            """,
            "CREATE INDEX IF NOT EXISTS idx_visit_requests_status ON visit_requests(status)",
            "CREATE INDEX IF NOT EXISTS idx_visit_requests_planned_from ON visit_requests(planned_from)",
            "CREATE INDEX IF NOT EXISTS idx_visit_requests_author ON visit_requests(author_user_id)",

            // 2. История переходов по заявке
            """
            CREATE TABLE IF NOT EXISTS visit_request_history (
                history_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                request_id    BIGINT NOT NULL,
                from_status   VARCHAR(32),
                to_status     VARCHAR(32) NOT NULL,
                action        VARCHAR(32) NOT NULL,
                comment       VARCHAR(1000),
                actor_user_id INTEGER,
                actor_email   VARCHAR(200),
                created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
                CONSTRAINT fk_history_request FOREIGN KEY (request_id)
                    REFERENCES visit_requests(request_id) ON DELETE CASCADE
            )
            """,
            "CREATE INDEX IF NOT EXISTS idx_history_request ON visit_request_history(request_id)",

            // 3. Уведомления
            """
            CREATE TABLE IF NOT EXISTS notifications (
                notification_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                recipient_user_id INTEGER NOT NULL,
                type              VARCHAR(40) NOT NULL,
                title             VARCHAR(200) NOT NULL,
                body              VARCHAR(1000),
                link              VARCHAR(300),
                is_read           BOOLEAN NOT NULL DEFAULT FALSE,
                created_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
            )
            """,
            "CREATE INDEX IF NOT EXISTS idx_notifications_recipient ON notifications(recipient_user_id, is_read)",

            // 4. Журнал аудита изменений
            """
            CREATE TABLE IF NOT EXISTS audit_log (
                audit_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                entity_type VARCHAR(40) NOT NULL,
                entity_id   VARCHAR(64) NOT NULL,
                action      VARCHAR(32) NOT NULL,
                actor_email VARCHAR(200),
                before_json TEXT,
                after_json  TEXT,
                reason      VARCHAR(500),
                created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
            )
            """,
            "CREATE INDEX IF NOT EXISTS idx_audit_entity ON audit_log(entity_type, entity_id)",
            "CREATE INDEX IF NOT EXISTS idx_audit_created_at ON audit_log(created_at)",

            // 5. Связь одобренной заявки с ожидаемым визитом
            "ALTER TABLE guest_visits ADD COLUMN IF NOT EXISTS request_id BIGINT",
            "CREATE INDEX IF NOT EXISTS idx_guest_visits_request ON guest_visits(request_id)",

            // 5.1. Оптимистичная блокировка заявки от двойного одобрения
            "ALTER TABLE visit_requests ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 0",

            // 6. Роли, которые нужны новому процессу согласования
            """
            INSERT INTO roles (role_id, name)
            SELECT 0, 'USER' WHERE NOT EXISTS (SELECT 1 FROM roles WHERE role_id = 0)
            """,
            """
            INSERT INTO roles (role_id, name)
            SELECT 1, 'ADMIN' WHERE NOT EXISTS (SELECT 1 FROM roles WHERE role_id = 1)
            """,
            """
            INSERT INTO roles (role_id, name)
            SELECT 2, 'APPROVER' WHERE NOT EXISTS (SELECT 1 FROM roles WHERE role_id = 2)
            """,
            """
            INSERT INTO roles (role_id, name)
            SELECT 3, 'SECURITY' WHERE NOT EXISTS (SELECT 1 FROM roles WHERE role_id = 3)
            """
    );

    private final DataSource dataSource;

    /** Сколько раз пробуем подключиться, прежде чем признать базу недоступной. */
    private static final int CONNECT_ATTEMPTS = 20;
    private static final long RETRY_DELAY_MS = 3_000L;

    @Override
    public void run(ApplicationArguments args) {
        Exception lastFailure = null;

        for (int attempt = 1; attempt <= CONNECT_ATTEMPTS; attempt++) {
            try (Connection connection = dataSource.getConnection();
                 Statement statement = connection.createStatement()) {
                applyMigrations(statement);
                log.info("Schema migration completed: заявки, история, уведомления и аудит готовы");
                return;
            } catch (SQLException ex) {
                // База может подниматься одновременно с приложением: без ожидания
                // контейнер бэкенда уходит в цикл перезапусков с длинным стектрейсом.
                lastFailure = ex;
                log.warn("База данных недоступна (попытка {}/{}): {}",
                        attempt, CONNECT_ATTEMPTS, ex.getMessage());
                pauseBeforeRetry();
            } catch (Exception ex) {
                throw new IllegalStateException("Не удалось применить миграции схемы: " + ex.getMessage(), ex);
            }
        }

        throw new IllegalStateException(
                "База данных недоступна, миграции не применены. Проверьте, что контейнер postgres_db запущен "
                        + "и совпадает с DB_URL", lastFailure);
    }

    private void applyMigrations(Statement statement) throws SQLException {
        // Дополнение из прошлой версии оставляем на месте
        statement.execute("ALTER TABLE personnel ADD COLUMN IF NOT EXISTS archived_at TIMESTAMP WITH TIME ZONE");
        statement.execute("CREATE INDEX IF NOT EXISTS idx_personnel_archived_at ON personnel(archived_at)");

        for (String sql : MIGRATIONS) {
            statement.execute(sql);
        }
    }

    private void pauseBeforeRetry() {
        try {
            Thread.sleep(RETRY_DELAY_MS);
        } catch (InterruptedException interrupted) {
            Thread.currentThread().interrupt();
            throw new IllegalStateException("Применение миграций прервано", interrupted);
        }
    }
}